-- Migración: Registro de clientes (autorizados e invitados / USUARIO_NO_AUTORIZADO),
-- verificación de regalo de primera compra (Bombón Ferrero en Esfera) y recarga de caché PostgREST.

-- 1. Tabla comun_comercio.com_cliente para capturar compradores registrados e invitados
create table if not exists comun_comercio.com_cliente (
  cli_id uuid primary key default gen_random_uuid(),
  cli_secuencial bigint generated by default as identity,
  cli_negocio text not null,
  cli_usuario_id uuid references comun_seguridad.seg_usuario(usu_id) on delete set null,
  cli_tipo_registro text not null default 'USUARIO_NO_AUTORIZADO'
    check (cli_tipo_registro in ('USUARIO_NO_AUTORIZADO', 'USUARIO_REGISTRADO')),
  cli_identificacion text,
  cli_nombre text not null,
  cli_correo text,
  cli_telefono text,
  cli_direccion text,
  cli_total_compras integer not null default 0,
  cli_monto_acumulado numeric(12,2) not null default 0,
  cli_regalo_primera_compra_entregado boolean not null default false,
  cli_primera_compra_en timestamptz,
  cli_ultima_compra_en timestamptz,
  cli_detalle_cliente jsonb not null default '{}'::jsonb,
  cli_creado_en timestamptz not null default now(),
  cli_actualizado_en timestamptz not null default now(),
  cli_eliminado_en timestamptz
);

create unique index if not exists idx_com_cliente_negocio_correo_unico
  on comun_comercio.com_cliente (cli_negocio, lower(cli_correo))
  where cli_correo is not null and cli_correo <> '' and cli_eliminado_en is null;

create unique index if not exists idx_com_cliente_negocio_usuario_unico
  on comun_comercio.com_cliente (cli_negocio, cli_usuario_id)
  where cli_usuario_id is not null and cli_eliminado_en is null;

create index if not exists idx_com_cliente_negocio_identificacion
  on comun_comercio.com_cliente (cli_negocio, cli_identificacion)
  where cli_identificacion is not null and cli_eliminado_en is null;

alter table comun_comercio.com_cliente enable row level security;

drop policy if exists com_cliente_lectura on comun_comercio.com_cliente;
create policy com_cliente_lectura on comun_comercio.com_cliente
  for select using (
    (auth.uid() is not null and cli_usuario_id = auth.uid())
    or comun_seguridad.seg_fn_es_admin_negocio(cli_negocio)
  );

drop policy if exists com_cliente_gestion_admin on comun_comercio.com_cliente;
create policy com_cliente_gestion_admin on comun_comercio.com_cliente
  for all using (
    comun_seguridad.seg_fn_es_admin_negocio(cli_negocio)
  ) with check (
    comun_seguridad.seg_fn_es_admin_negocio(cli_negocio)
  );

drop trigger if exists trg_auditoria_com_cliente on comun_comercio.com_cliente;
create trigger trg_auditoria_com_cliente
  after insert or update or delete on comun_comercio.com_cliente
  for each row execute function comun_auditoria.aud_fn_auditar_tabla();

grant select on comun_comercio.com_cliente to authenticated;
grant all on comun_comercio.com_cliente to service_role;

-- 2. Función interna para capturar/actualizar información del cliente en cada pedido o pago
create or replace function comun_comercio.com_fn_capturar_cliente_compra(
  p_negocio text,
  p_usuario_id uuid,
  p_comprador jsonb,
  p_monto_confirmado numeric default null,
  p_incluye_regalo boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_negocio text := lower(trim(coalesce(p_negocio, 'tinkay')));
  v_nombre text := coalesce(nullif(trim(p_comprador->>'nombreCompleto'), ''), nullif(trim(p_comprador->>'nombre'), ''), 'Cliente');
  v_identificacion text := nullif(trim(coalesce(p_comprador->>'identificacion', '')), '');
  v_correo text := nullif(lower(trim(coalesce(p_comprador->>'correo', p_comprador->>'email', ''))), '');
  v_telefono text := nullif(trim(coalesce(p_comprador->>'telefono', '')), '');
  v_direccion text := nullif(trim(coalesce(p_comprador->>'direccion', '')), '');
  v_tipo text := case when p_usuario_id is not null then 'USUARIO_REGISTRADO' else 'USUARIO_NO_AUTORIZADO' end;
  v_cli_id uuid;
begin
  if p_usuario_id is not null then
    select cli_id into v_cli_id
    from comun_comercio.com_cliente
    where cli_negocio = v_negocio
      and cli_usuario_id = p_usuario_id
      and cli_eliminado_en is null
    limit 1;
  end if;

  if v_cli_id is null and v_correo is not null then
    select cli_id into v_cli_id
    from comun_comercio.com_cliente
    where cli_negocio = v_negocio
      and lower(cli_correo) = v_correo
      and cli_eliminado_en is null
    limit 1;
  end if;

  if v_cli_id is null and v_identificacion is not null then
    select cli_id into v_cli_id
    from comun_comercio.com_cliente
    where cli_negocio = v_negocio
      and cli_identificacion = v_identificacion
      and cli_eliminado_en is null
    limit 1;
  end if;

  if v_cli_id is null then
    insert into comun_comercio.com_cliente (
      cli_negocio,
      cli_usuario_id,
      cli_tipo_registro,
      cli_identificacion,
      cli_nombre,
      cli_correo,
      cli_telefono,
      cli_direccion,
      cli_total_compras,
      cli_monto_acumulado,
      cli_regalo_primera_compra_entregado,
      cli_primera_compra_en,
      cli_ultima_compra_en,
      cli_detalle_cliente
    )
    values (
      v_negocio,
      p_usuario_id,
      v_tipo,
      v_identificacion,
      v_nombre,
      v_correo,
      v_telefono,
      v_direccion,
      case when p_monto_confirmado is not null then 1 else 0 end,
      coalesce(p_monto_confirmado, 0),
      coalesce(p_incluye_regalo, false),
      case when p_monto_confirmado is not null then now() else null end,
      now(),
      jsonb_build_object(
        'ultimo_origen', case when p_usuario_id is null then 'COMPRA_USUARIO_NO_AUTORIZADO' else 'COMPRA_USUARIO_REGISTRADO' end,
        'datos_capturados', coalesce(p_comprador, '{}'::jsonb)
      )
    )
    returning cli_id into v_cli_id;
  else
    update comun_comercio.com_cliente
       set cli_usuario_id = coalesce(cli_usuario_id, p_usuario_id),
           cli_tipo_registro = case
             when coalesce(cli_usuario_id, p_usuario_id) is not null then 'USUARIO_REGISTRADO'
             else cli_tipo_registro
           end,
           cli_identificacion = coalesce(v_identificacion, cli_identificacion),
           cli_nombre = case when v_nombre <> 'Cliente' then v_nombre else cli_nombre end,
           cli_correo = coalesce(v_correo, cli_correo),
           cli_telefono = coalesce(v_telefono, cli_telefono),
           cli_direccion = coalesce(v_direccion, cli_direccion),
           cli_total_compras = cli_total_compras + case when p_monto_confirmado is not null then 1 else 0 end,
           cli_monto_acumulado = cli_monto_acumulado + coalesce(p_monto_confirmado, 0),
           cli_regalo_primera_compra_entregado = cli_regalo_primera_compra_entregado or coalesce(p_incluye_regalo, false),
           cli_primera_compra_en = coalesce(cli_primera_compra_en, case when p_monto_confirmado is not null then now() else null end),
           cli_ultima_compra_en = now(),
           cli_actualizado_en = now(),
           cli_detalle_cliente = coalesce(cli_detalle_cliente, '{}'::jsonb) || jsonb_build_object(
             'ultimo_origen', case when coalesce(cli_usuario_id, p_usuario_id) is null then 'COMPRA_USUARIO_NO_AUTORIZADO' else 'COMPRA_USUARIO_REGISTRADO' end,
             'datos_capturados', coalesce(p_comprador, '{}'::jsonb)
           )
     where cli_id = v_cli_id;
  end if;

  return v_cli_id;
end;
$$;

revoke execute on function comun_comercio.com_fn_capturar_cliente_compra(text, uuid, jsonb, numeric, boolean) from public;
grant execute on function comun_comercio.com_fn_capturar_cliente_compra(text, uuid, jsonb, numeric, boolean) to service_role;

-- 3. Actualizar com_fn_registrar_pedido_tienda para etiquetar USUARIO_NO_AUTORIZADO / USUARIO_REGISTRADO
-- y guardar siempre los datos capturados del cliente en com_cliente
create or replace function comun_comercio.com_fn_registrar_pedido_tienda(
  p_negocio text,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_negocio text := lower(trim(coalesce(p_negocio, 'tinkay')));
  v_prefijo text := case
    when v_negocio like '%tinkay%' then 'TNK'
    when v_negocio like '%margarita%' then 'MRG'
    when v_negocio like '%fastfix%' then 'FFH'
    else 'TRQ'
  end;
  v_usuario uuid := auth.uid();
  v_comprador jsonb := coalesce(p_payload->'comprador', '{}'::jsonb);
  v_items jsonb := coalesce(p_payload->'items', '[]'::jsonb);
  v_logistica jsonb := coalesce(p_payload->'logistica_entrega', '{}'::jsonb);
  v_estado_inicial text := coalesce(nullif(trim(p_payload->>'estado'), ''), 'PENDIENTE_PAGO');
  v_subtotal numeric(12,2) := greatest(0, coalesce((p_payload->>'subtotal_base_imponible')::numeric(12,2), 0));
  v_iva numeric(12,2) := greatest(0, coalesce((p_payload->>'total_iva')::numeric(12,2), 0));
  v_total numeric(12,2) := greatest(0, coalesce((p_payload->>'total_pagar')::numeric(12,2), 0));
  v_tipo_comprador text := case when v_usuario is not null then 'USUARIO_REGISTRADO' else 'USUARIO_NO_AUTORIZADO' end;
  v_cli_id uuid;
  v_prf_id uuid;
  v_secuencial bigint;
  v_token text;
  v_codigo text;
  v_item jsonb;
  v_payload_final jsonb;
begin
  if jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    return jsonb_build_object('ok', false, 'error', 'El pedido debe incluir al menos un producto.');
  end if;

  if v_estado_inicial not in ('PENDIENTE_PAGO', 'APROBADA') then
    v_estado_inicial := 'PENDIENTE_PAGO';
  end if;

  v_cli_id := comun_comercio.com_fn_capturar_cliente_compra(
    v_negocio,
    v_usuario,
    v_comprador,
    null,
    (p_payload ? 'regalo_primera_compra')
  );

  v_payload_final := p_payload || jsonb_build_object(
    'tipo_comprador', v_tipo_comprador,
    'usuario_autorizado', (v_usuario is not null),
    'cliente_capturado_id', v_cli_id
  );

  insert into comun_comercio.com_proforma (
    prf_negocio, prf_cliente_id, prf_cliente_nombre, prf_cliente_contacto, prf_estado,
    prf_subtotal, prf_descuento, prf_iva, prf_total, prf_observaciones, prf_detalle_proforma
  )
  values (
    v_negocio, v_usuario,
    coalesce(nullif(trim(v_comprador->>'nombreCompleto'), ''), 'Cliente'),
    v_comprador || jsonb_build_object('tipo_comprador', v_tipo_comprador),
    v_estado_inicial, v_subtotal, 0, v_iva, v_total,
    coalesce(p_payload->>'observaciones', ''),
    v_payload_final
  )
  returning prf_id, prf_secuencial, prf_token_aprobacion
  into v_prf_id, v_secuencial, v_token;

  v_codigo := v_prefijo || '-ORD-' || lpad(coalesce(v_secuencial, 1)::text, 4, '0');

  update comun_comercio.com_proforma
     set prf_detalle_proforma = prf_detalle_proforma || jsonb_build_object('codigo_orden', v_codigo)
   where prf_id = v_prf_id;

  for v_item in select * from jsonb_array_elements(v_items) loop
    insert into comun_comercio.com_proforma_item (
      pfi_negocio, pfi_proforma_id, pfi_variante_id, pfi_es_item_libre,
      pfi_descripcion, pfi_cantidad, pfi_precio_unitario, pfi_descuento,
      pfi_impuesto, pfi_total_linea, pfi_detalle_item
    )
    values (
      v_negocio, v_prf_id, null, true,
      coalesce(v_item->>'descripcion', v_item->>'producto_nombre', 'Producto'),
      greatest(0.01, coalesce((v_item->>'cantidad')::numeric(10,2), 1)),
      greatest(0, coalesce((v_item->>'precio_unitario')::numeric(12,2), 0)),
      0,
      coalesce(v_item->>'impuesto', 'IVA_0'),
      greatest(0, coalesce((v_item->>'total_linea')::numeric(12,2), 0)),
      v_item
    );
  end loop;

  insert into comun_comercio.com_despacho_asignacion (
    dsp_negocio, dsp_orden_id, dsp_modalidad, dsp_tracking_url, dsp_costo_envio,
    dsp_estado, dsp_observaciones_coordinacion, dsp_detalle_despacho
  )
  values (
    v_negocio, v_prf_id,
    case when coalesce((v_logistica->>'retiro_en_local')::boolean, false) then 'RETIRO_LOCAL' else 'PROPIO' end,
    v_logistica->>'enlace_mapa',
    greatest(0, coalesce((p_payload->>'total_flete')::numeric(12,2), 0)),
    'ASIGNADO',
    coalesce(v_logistica->>'formula_calculo_interno', p_payload->>'observaciones', ''),
    v_logistica
  );

  return jsonb_build_object(
    'ok', true,
    'id', v_prf_id,
    'codigo_orden', v_codigo,
    'token_aprobacion', v_token,
    'tipo_comprador', v_tipo_comprador
  );
end;
$$;

revoke execute on function comun_comercio.com_fn_registrar_pedido_tienda(text, jsonb) from public;
grant execute on function comun_comercio.com_fn_registrar_pedido_tienda(text, jsonb) to anon, authenticated, service_role;

-- 4. RPC para verificar si el usuario autenticado califica al regalo de primera compra
create or replace function comun_comercio.com_fn_verificar_primera_compra_usuario(
  p_negocio text default 'tinkay'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_negocio text := lower(trim(coalesce(p_negocio, 'tinkay')));
  v_email text;
  v_compras_previas integer := 0;
  v_regalo_entregado boolean := false;
begin
  if v_usuario is null then
    return jsonb_build_object(
      'autenticado', false,
      'aplica_regalo', false,
      'regalo', jsonb_build_object(
        'sku', 'TIN-VAR-6',
        'nombre', 'Bombón Ferrero x1 en Esfera Acrílica',
        'valor_referencia', 1.50
      )
    );
  end if;

  select lower(trim(coalesce(usu_correo, '')))
    into v_email
    from comun_seguridad.seg_usuario
   where usu_id = v_usuario;

  select coalesce(bool_or(cli_regalo_primera_compra_entregado), false)
    into v_regalo_entregado
    from comun_comercio.com_cliente
   where cli_negocio = v_negocio
     and (cli_usuario_id = v_usuario or (v_email <> '' and lower(cli_correo) = v_email))
     and cli_eliminado_en is null;

  if not v_regalo_entregado then
    select count(*)
      into v_compras_previas
      from comun_comercio.com_proforma
     where prf_negocio = v_negocio
       and prf_eliminado_en is null
       and prf_estado in ('APROBADA', 'RESERVADA_70', 'EN_PRODUCCION', 'EN_CAMINO', 'ENTREGADO')
       and (
         prf_cliente_id = v_usuario
         or (v_email <> '' and lower(coalesce(prf_cliente_contacto->>'correo', '')) = v_email)
       );
  end if;

  return jsonb_build_object(
    'autenticado', true,
    'aplica_regalo', (not v_regalo_entregado and v_compras_previas = 0),
    'regalo', jsonb_build_object(
      'sku', 'TIN-VAR-6',
      'nombre', 'Bombón Ferrero x1 en Esfera Acrílica',
      'valor_referencia', 1.50
    )
  );
end;
$$;

revoke execute on function comun_comercio.com_fn_verificar_primera_compra_usuario(text) from public;
grant execute on function comun_comercio.com_fn_verificar_primera_compra_usuario(text) to anon, authenticated, service_role;

-- 5. Crear o reemplazar com_fn_preparar_pago_plux_proforma y recargar caché de PostgREST
create or replace function comun_comercio.com_fn_preparar_pago_plux_proforma(
  p_negocio text,
  p_proforma_id uuid,
  p_token text,
  p_pagador jsonb,
  p_modalidad_cobro text default 'TOTAL_100'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_negocio text := lower(trim(coalesce(p_negocio, 'tinkay')));
  v_prefijo text := case
    when v_negocio like '%tinkay%' then 'TNK'
    when v_negocio like '%margarita%' then 'MRG'
    when v_negocio like '%fastfix%' then 'FFH'
    else 'TRQ'
  end;
  v_modalidad text := upper(trim(coalesce(p_modalidad_cobro, 'TOTAL_100')));
  v_pasarela comun_comercio.com_pasarela_configuracion%rowtype;
  v_prf comun_comercio.com_proforma%rowtype;
  v_total_orden_c bigint;
  v_iva_orden_c bigint;
  v_base_orden_c bigint;
  v_base_grav_orden_c bigint;
  v_base0_orden_c bigint;
  v_abonado_prev_c bigint;
  v_restante_c bigint;
  v_factor numeric;
  v_base0_c bigint;
  v_base_grav_c bigint;
  v_iva_c bigint;
  v_total_c bigint;
  v_codigo text;
  v_etiqueta_cobro text;
  v_identificador text;
begin
  if v_modalidad not in ('TOTAL_100', 'RESERVA_70', 'SALDO_30') then
    return jsonb_build_object('ok', false, 'error', 'Modalidad de cobro no válida.');
  end if;

  select * into v_pasarela
  from comun_comercio.com_pasarela_configuracion
  where psc_negocio = v_negocio
    and psc_pasarela = 'PLUX'
    and psc_activo = true
    and psc_eliminado_en is null;

  if not found and v_negocio <> 'tranqi' then
    select * into v_pasarela
    from comun_comercio.com_pasarela_configuracion
    where psc_negocio = 'tranqi'
      and psc_pasarela = 'PLUX'
      and psc_activo = true
      and psc_eliminado_en is null;
  end if;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'La pasarela PLUX no está activa para este comercio.');
  end if;

  select * into v_prf
  from comun_comercio.com_proforma
  where prf_id = p_proforma_id
    and prf_negocio = v_negocio
    and prf_eliminado_en is null;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'La orden o proforma no fue encontrada.');
  end if;

  if not (
    (p_token is not null and v_prf.prf_token_aprobacion = trim(p_token))
    or (v_usuario is not null and v_prf.prf_cliente_id = v_usuario)
  ) then
    return jsonb_build_object('ok', false, 'error', 'No autorizado para procesar el pago de esta proforma.');
  end if;

  if v_prf.prf_estado in ('CANCELADO', 'ENTREGADO') then
    return jsonb_build_object('ok', false, 'error', 'Esta orden ya no admite cobros en línea.');
  end if;

  v_total_orden_c := round(coalesce(v_prf.prf_total, 0) * 100);
  v_iva_orden_c := greatest(0, round(coalesce(v_prf.prf_iva, 0) * 100));
  v_base_orden_c := greatest(0, v_total_orden_c - v_iva_orden_c);

  if (v_prf.prf_detalle_proforma ? 'base_iva_gravada_centavos') and (v_prf.prf_detalle_proforma ? 'base_iva_0_centavos') then
    v_base_grav_orden_c := greatest(0, (v_prf.prf_detalle_proforma->>'base_iva_gravada_centavos')::bigint);
    v_base0_orden_c := greatest(0, v_base_orden_c - v_base_grav_orden_c);
  elsif v_iva_orden_c > 0 then
    v_base_grav_orden_c := least(v_base_orden_c, round(v_iva_orden_c * 100.0 / 15.0));
    v_base0_orden_c := greatest(0, v_base_orden_c - v_base_grav_orden_c);
  else
    v_base_grav_orden_c := 0;
    v_base0_orden_c := v_base_orden_c;
  end if;

  v_abonado_prev_c := greatest(0, round(coalesce((v_prf.prf_detalle_proforma->>'monto_abonado_usd')::numeric, 0) * 100));

  if v_prf.prf_estado = 'APROBADA' and v_abonado_prev_c >= v_total_orden_c then
    return jsonb_build_object('ok', false, 'error', 'Esta proforma ya se encuentra pagada al 100%.');
  end if;

  if v_modalidad = 'RESERVA_70' then
    if v_prf.prf_estado = 'RESERVADA_70' or v_abonado_prev_c > 0 then
      return jsonb_build_object('ok', false, 'error', 'La reserva del 70% ya fue registrada. Puedes abonar el saldo restante.');
    end if;
    v_base0_c := round(v_base0_orden_c * 0.70);
    v_base_grav_c := round(v_base_grav_orden_c * 0.70);
    v_iva_c := round(v_iva_orden_c * 0.70);
    v_total_c := v_base0_c + v_base_grav_c + v_iva_c;
    v_etiqueta_cobro := 'Reserva 70% Evento';
  elsif v_modalidad = 'SALDO_30' or v_abonado_prev_c > 0 then
    v_restante_c := greatest(0, v_total_orden_c - v_abonado_prev_c);
    if v_restante_c <= 0 then
      return jsonb_build_object('ok', false, 'error', 'No existe saldo pendiente por pagar.');
    end if;
    v_factor := v_restante_c::numeric / greatest(1, v_total_orden_c)::numeric;
    v_iva_c := round(v_iva_orden_c * v_factor);
    v_base_grav_c := round(v_base_grav_orden_c * v_factor);
    v_base0_c := greatest(0, v_restante_c - v_iva_c - v_base_grav_c);
    v_total_c := v_base0_c + v_base_grav_c + v_iva_c;
    v_modalidad := 'SALDO_30';
    v_etiqueta_cobro := 'Liquidación Saldo 30%';
  else
    v_base0_c := v_base0_orden_c;
    v_base_grav_c := v_base_grav_orden_c;
    v_iva_c := v_iva_orden_c;
    v_total_c := v_base0_c + v_base_grav_c + v_iva_c;
    v_etiqueta_cobro := 'Pago Total 100%';
  end if;

  if v_total_c <= 0 then
    return jsonb_build_object('ok', false, 'error', 'El importe a cobrar debe ser mayor a cero.');
  end if;

  v_codigo := coalesce(
    v_prf.prf_detalle_proforma->>'codigo_proforma',
    v_prf.prf_detalle_proforma->>'codigo_orden',
    v_prefijo || '-PRF-' || lpad(coalesce(v_prf.prf_secuencial, 1)::text, 4, '0')
  );
  v_identificador := v_prefijo || '-PLX-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));

  insert into comun_comercio.com_transaccion_pago (
    pag_negocio, pag_cliente_id, pag_pasarela, pag_identificador_cliente, pag_estado,
    pag_monto_total, pag_monto_con_iva, pag_monto_sin_iva, pag_monto_iva, pag_moneda,
    pag_referencia_id, pag_titular_email, pag_titular_telefono, pag_titular_identificacion,
    pag_detalle_transaccion
  )
  values (
    v_negocio, coalesce(v_usuario, v_prf.prf_cliente_id), 'PLUX', v_identificador, 'PENDIENTE',
    v_total_c / 100.0, v_base_grav_c / 100.0, v_base0_c / 100.0, v_iva_c / 100.0, 'USD',
    v_prf.prf_id, p_pagador->>'email', p_pagador->>'telefono', p_pagador->>'identificacion',
    jsonb_build_object(
      'proforma_id', v_prf.prf_id,
      'codigo_orden', v_codigo,
      'modalidad_cobro', v_modalidad,
      'producto', v_codigo || ' (' || v_etiqueta_cobro || ')',
      'base0_centavos', v_base0_c,
      'base_gravada_centavos', v_base_grav_c,
      'iva_centavos', v_iva_c,
      'ambiente', v_pasarela.psc_ambiente,
      'pagador', p_pagador
    )
  );

  return jsonb_build_object(
    'ok', true,
    'identificador', v_identificador,
    'ambiente', v_pasarela.psc_ambiente,
    'remail', coalesce(v_pasarela.psc_credenciales_publicas->>'remail', 'admin.operaciones@tranqi24.com'),
    'nombre_comercio', coalesce(v_pasarela.psc_credenciales_publicas->>'nombre_comercio', initcap(v_negocio)),
    'descripcion', v_codigo || ' - ' || v_etiqueta_cobro,
    'base_centavos', v_base0_c + v_base_grav_c,
    'base0_centavos', v_base0_c,
    'base_gravada_centavos', v_base_grav_c,
    'iva_centavos', v_iva_c,
    'total_centavos', v_total_c
  );
end;
